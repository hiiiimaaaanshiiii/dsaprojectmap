#!/usr/bin/env python3
"""Convert a bounded OpenStreetMap XML extract into Map Navigator's CSV road graph.

Usage:
  python3 backend/tools/osm_to_graph.py input.osm backend/data/delhi_graph.csv

Use a regional OSM XML extract that you are permitted to download. This intentionally
does not query a public OSM API itself. The generated graph honours one-way ways and
keeps drivable highway classes; turn restrictions are a planned next-stage extension.
"""

from __future__ import annotations

import csv
import re
import sys
import xml.etree.ElementTree as element_tree
from collections import defaultdict
from pathlib import Path

DRIVABLE = {
    "motorway", "trunk", "primary", "secondary", "tertiary", "unclassified",
    "residential", "service", "motorway_link", "trunk_link", "primary_link",
    "secondary_link", "tertiary_link",
}
DEFAULT_SPEED_KPH = {
    "motorway": 80, "trunk": 65, "primary": 50, "secondary": 40,
    "tertiary": 35, "unclassified": 30, "residential": 25, "service": 15,
    "motorway_link": 45, "trunk_link": 40, "primary_link": 35,
    "secondary_link": 30, "tertiary_link": 25,
}


def tags(element: element_tree.Element) -> dict[str, str]:
    return {child.attrib["k"]: child.attrib["v"] for child in element if child.tag == "tag"}


def speed_kph(value: str | None, highway: str) -> int:
    if value:
        match = re.search(r"\d+(?:\.\d+)?", value)
        if match:
            speed = float(match.group())
            return round(speed * 1.60934) if "mph" in value.lower() else round(speed)
    return DEFAULT_SPEED_KPH[highway]


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    source, destination = map(Path, sys.argv[1:])
    if source.suffix.lower() != ".osm":
        print("Expected an OSM XML file (.osm), not a PBF. Convert PBF first if needed.", file=sys.stderr)
        return 2

    coordinates: dict[str, tuple[str, str]] = {}
    raw_edges: list[tuple[str, str, str, int, str]] = []
    for _, element in element_tree.iterparse(source, events=("end",)):
        if element.tag == "node":
            coordinates[element.attrib["id"]] = (element.attrib["lat"], element.attrib["lon"])
            element.clear()
        elif element.tag == "way":
            metadata = tags(element)
            highway = metadata.get("highway")
            if highway in DRIVABLE and metadata.get("access") not in {"no", "private"}:
                refs = [child.attrib["ref"] for child in element if child.tag == "nd"]
                road_name = metadata.get("name") or metadata.get("ref") or highway.replace("_", " ").title()
                direction = "F" if metadata.get("oneway") in {"yes", "1", "true"} else "B"
                speed = speed_kph(metadata.get("maxspeed"), highway)
                for first, second in zip(refs, refs[1:]):
                    if first in coordinates and second in coordinates:
                        raw_edges.append((first, second, road_name, speed, direction))
            element.clear()

    used_node_ids = sorted({node_id for edge in raw_edges for node_id in edge[:2]}, key=int)
    index = {node_id: number for number, node_id in enumerate(used_node_ids)}
    destination.parent.mkdir(parents=True, exist_ok=True)
    with destination.open("w", newline="", encoding="utf-8") as output:
        writer = csv.writer(output, delimiter="|", lineterminator="\n")
        writer.writerow(["# Generated by osm_to_graph.py", "OSM XML input", source.name])
        for osm_id in used_node_ids:
            latitude, longitude = coordinates[osm_id]
            writer.writerow(["N", index[osm_id], latitude, longitude, f"OSM node {osm_id}"])
        for first, second, name, speed, direction in raw_edges:
            writer.writerow(["E", index[first], index[second], name, speed, direction])
    print(f"Wrote {len(used_node_ids)} nodes and {len(raw_edges)} road segments to {destination}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
